package com.airtribe.wallet;

import com.airtribe.wallet.support.IntegrationTest;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * Not part of the normal build (tagged "perf"). Run with:
 *   ./mvnw test -Dtest.excludedGroups= -Dtest=PerformanceReportTest
 * Seeds ~1,000,000 ledger entries, then writes EXPLAIN ANALYZE output for every reconciliation check,
 * OFFSET vs cursor pagination, the fraud-rule queries, and measured per-transfer rule overhead to
 * docs/perf/explain-output.md.
 */
@Tag("perf")
class PerformanceReportTest extends IntegrationTest {

    private final List<String> out = new ArrayList<>();

    @Test
    void report() throws Exception {
        long t0 = System.currentTimeMillis();
        jdbc.execute(Files.readString(Path.of("scripts/seed.sql")));
        jdbc.execute("CALL seed_wallet_data(1000, 2000, 400000)");

        // one very busy wallet so that OFFSET 100000 lands inside a single statement
        long hot = jdbc.queryForObject("SELECT min(id) FROM accounts WHERE kind = 'USER_WALLET'", Long.class);
        jdbc.execute("ALTER TABLE ledger_entries DISABLE TRIGGER ledger_entries_balanced");
        jdbc.update("""
                WITH w AS (SELECT array_agg(id ORDER BY id) AS ids
                             FROM accounts WHERE kind = 'USER_WALLET' AND id <> ?),
                t AS (
                    INSERT INTO transfers (type, status, amount, from_account_id, to_account_id, initiated_by, created_at)
                    SELECT 'PEER', 'COMPLETED', 100, w.ids[1 + g % array_length(w.ids, 1)], ?, 'perf',
                           now() - random() * interval '59 days'
                      FROM generate_series(1, 120000) g, w
                    RETURNING id, from_account_id, to_account_id, amount, created_at)
                INSERT INTO ledger_entries (transfer_id, account_id, direction, amount, created_at)
                SELECT id, from_account_id, 'DEBIT', amount, created_at FROM t
                UNION ALL
                SELECT id, to_account_id, 'CREDIT', amount, created_at FROM t
                """, hot, hot);
        jdbc.execute("ALTER TABLE ledger_entries ENABLE TRIGGER ledger_entries_balanced");
        jdbc.update("""
                UPDATE accounts a SET balance = c.computed
                  FROM (SELECT account_id, SUM(CASE WHEN direction = 'CREDIT' THEN amount ELSE -amount END) computed
                          FROM ledger_entries GROUP BY account_id) c
                 WHERE c.account_id = a.id
                """);
        jdbc.execute("VACUUM ANALYZE");
        long seededMs = System.currentTimeMillis() - t0;

        Map<String, Object> counts = jdbc.queryForMap("""
                SELECT (SELECT count(*) FROM ledger_entries) AS entries, (SELECT count(*) FROM transfers) AS transfers,
                       (SELECT count(*) FROM accounts) AS accounts,
                       (SELECT count(*) FROM ledger_entries WHERE account_id = %d) AS hot_entries
                """.formatted(hot));
        out.add("# EXPLAIN ANALYZE output");
        out.add("");
        out.add("Generated by `PerformanceReportTest` on PostgreSQL "
                + jdbc.queryForObject("SHOW server_version", String.class) + ". Data: " + counts
                + " (seeded in " + seededMs / 1000 + " s). Wallet " + hot + " is the busy wallet.");

        explain("Check 1 - everything balances", com_recon("CHECK_LEDGER_BALANCED"));
        explain("Check 2 - every transfer balances", com_recon("CHECK_TRANSFERS_BALANCED"));
        explain("Check 3 - stored balances match entries", com_recon("CHECK_STORED_BALANCES"));
        explain("Check 4 - no overdrafts", com_recon("CHECK_NO_OVERDRAFT"));
        explain("Check 5a - completed transfers without entries", com_recon("CHECK_TRANSFERS_WITHOUT_ENTRIES"));
        explain("Check 5b - held/rejected transfers with entries", com_recon("CHECK_UNSETTLED_WITH_ENTRIES"));
        explain("Check 5c - entries without a transfer", com_recon("CHECK_ENTRIES_WITHOUT_TRANSFER"));

        String statement = """
                SELECT e.id, e.transfer_id, e.direction, e.amount, e.created_at
                  FROM ledger_entries e
                 WHERE e.account_id = %d
                 ORDER BY e.created_at DESC, e.id DESC
                """.formatted(hot);
        explain("Statement page 1 (OFFSET 0)", statement + " LIMIT 50 OFFSET 0");
        explain("Statement deep page (OFFSET 100000)", statement + " LIMIT 50 OFFSET 100000");
        Map<String, Object> cursorRow = jdbc.queryForMap("SELECT id, created_at::text AS created_at FROM ("
                + statement + " LIMIT 1 OFFSET 99999) x");
        explain("Statement deep page with a cursor (same rows as OFFSET 100000)", """
                SELECT e.id, e.transfer_id, e.direction, e.amount, e.created_at
                  FROM ledger_entries e
                 WHERE e.account_id = %d
                   AND (e.created_at, e.id) < ('%s'::timestamptz, %d)
                 ORDER BY e.created_at DESC, e.id DESC
                 LIMIT 50
                """.formatted(hot, cursorRow.get("created_at"), ((Number) cursorRow.get("id")).longValue()));

        long busySender = jdbc.queryForObject(
                "SELECT from_account_id FROM transfers WHERE type = 'PEER' GROUP BY 1 ORDER BY count(*) DESC LIMIT 1",
                Long.class);
        explain("Rule VELOCITY", """
                SELECT count(*) FROM transfers
                 WHERE from_account_id = %d AND created_at > now() - make_interval(mins => 10)
                   AND type IN ('PEER', 'WITHDRAWAL') AND status IN ('COMPLETED', 'HELD', 'REVERSED')
                """.formatted(busySender));
        explain("Rule AMOUNT_SPIKE", """
                SELECT avg(amount)::bigint, count(*) FROM transfers
                 WHERE from_account_id = %d AND created_at > now() - make_interval(days => 30)
                   AND type IN ('PEER', 'WITHDRAWAL') AND status IN ('COMPLETED', 'REVERSED')
                """.formatted(busySender));
        explain("Rule NEW_PAYEE_LARGE", """
                SELECT EXISTS (SELECT 1 FROM transfers WHERE from_account_id = %d AND to_account_id = %d
                                  AND status IN ('COMPLETED', 'REVERSED'))
                """.formatted(busySender, hot));

        // measured overhead of the rules on a real transfer (HTTP round trip included)
        long a = walletFor("Bench A");
        long b = walletFor("Bench B");
        topUp(a, 100_000_000);
        String off = "UPDATE risk_rules SET enabled = false";
        String on = "UPDATE risk_rules SET enabled = true, max_count = 1000000, multiplier = 99999, "
                + "amount_threshold = 1000000000000";
        jdbc.update(on);
        timeTransfers(a, b, 200); // warm-up (JIT, connection pool, plan cache)
        double without = 0;
        double with = 0;
        int rounds = 6;
        for (int r = 0; r < rounds; r++) { // alternate so drift affects both sides equally
            jdbc.update(off);
            without += timeTransfers(a, b, 100);
            jdbc.update(on);
            with += timeTransfers(a, b, 100);
        }
        without /= rounds;
        with /= rounds;
        out.add("");
        out.add("## Fraud-rule overhead per transfer");
        out.add("");
        out.add(String.format("6 alternating rounds of 100 sequential transfers (HTTP round trip included) from a wallet "
                + "with history: rules off %.2f ms avg, rules on (all three evaluated, none firing) %.2f ms avg, "
                + "difference %.2f ms. The rule queries themselves cost 0.07-1.1 ms each in the plans above.",
                without, with, with - without));

        Files.createDirectories(Path.of("docs/perf"));
        Files.write(Path.of("docs/perf/explain-output.md"), out);
    }

    private double timeTransfers(long a, long b, int n) {
        long start = System.nanoTime();
        for (int i = 0; i < n; i++) {
            transfer(a, b, 1);
        }
        return (System.nanoTime() - start) / 1e6 / n;
    }

    private static String com_recon(String field) throws Exception {
        var f = com.airtribe.wallet.recon.ReconciliationService.class.getDeclaredField(field);
        f.setAccessible(true);
        return (String) f.get(null);
    }

    private void explain(String title, String sql) {
        List<String> plan = jdbc.queryForList("EXPLAIN (ANALYZE, BUFFERS) " + sql, String.class);
        out.add("");
        out.add("## " + title);
        out.add("");
        out.add("```sql");
        out.add(sql.strip());
        out.add("```");
        out.add("");
        out.add("```");
        out.addAll(plan);
        out.add("```");
    }
}
