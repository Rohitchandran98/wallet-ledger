-- =====================================================================
-- Wallet ledger schema. See docs/schema.md for the noun list,
-- cardinalities and ER diagram.
--
-- Conventions
--   * every table: system-generated BIGINT primary key
--   * plural snake_case tables, singular columns
--   * money: whole paise in BIGINT, never FLOAT/NUMERIC
--   * direction convention: DEBIT = money leaves the account,
--                           CREDIT = money enters the account
--     so  balance = SUM(credits) - SUM(debits)
-- =====================================================================

-- ---------------------------------------------------------------------
-- users: people who own wallets. email/phone are user-supplied, can
-- change, and are therefore UNIQUE but never the primary key.
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT        NOT NULL CHECK (length(btrim(name)) > 0),
    email       TEXT        NOT NULL CHECK (position('@' IN email) > 1),
    phone       TEXT        NOT NULL CHECK (phone ~ '^\+?[0-9]{8,15}$'),
    kyc_status  TEXT        NOT NULL DEFAULT 'PENDING'
                            CHECK (kyc_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_uq ON users (lower(email));
CREATE UNIQUE INDEX users_phone_uq ON users (phone);

-- ---------------------------------------------------------------------
-- accounts: user wallets AND system accounts (cash-in, cash-out, fee
-- revenue) in ONE table, so a ledger entry always points to exactly one
-- account through a single, enforceable foreign key.
-- ---------------------------------------------------------------------
CREATE TABLE accounts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      REFERENCES users (id),
    kind        TEXT        NOT NULL CHECK (kind IN ('USER_WALLET', 'SYSTEM')),
    system_code TEXT        UNIQUE CHECK (system_code IN ('CASH_IN', 'CASH_OUT', 'FEE_REVENUE')),
    name        TEXT        NOT NULL,
    currency    CHAR(3)     NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    -- cached balance, maintained inside the same transaction that writes
    -- the ledger entries; verified nightly against the entries.
    balance     BIGINT      NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT accounts_owner_ck CHECK (
        (kind = 'USER_WALLET' AND user_id IS NOT NULL AND system_code IS NULL)
     OR (kind = 'SYSTEM'      AND user_id IS NULL     AND system_code IS NOT NULL)),
    -- a user wallet can never go below zero; system accounts may
    CONSTRAINT accounts_wallet_non_negative_ck CHECK (kind = 'SYSTEM' OR balance >= 0)
);
CREATE INDEX accounts_user_idx ON accounts (user_id) WHERE user_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- transfers: the business event. Money moves only through a transfer.
-- A HELD/REJECTED transfer has no ledger entries (no money moved).
-- ---------------------------------------------------------------------
CREATE TABLE transfers (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                 TEXT        NOT NULL
                                     CHECK (type IN ('TOPUP', 'PEER', 'WITHDRAWAL', 'FEE', 'REVERSAL')),
    status               TEXT        NOT NULL
                                     CHECK (status IN ('HELD', 'COMPLETED', 'REJECTED', 'REVERSED')),
    amount               BIGINT      NOT NULL CHECK (amount > 0),
    from_account_id      BIGINT      NOT NULL REFERENCES accounts (id),
    to_account_id        BIGINT      NOT NULL REFERENCES accounts (id),
    -- a reversal points at the transfer it undoes; UNIQUE => at most one reversal each
    reverses_transfer_id BIGINT      UNIQUE REFERENCES transfers (id),
    -- a fee transfer points at the withdrawal it was charged for
    parent_transfer_id   BIGINT      REFERENCES transfers (id),
    initiated_by         TEXT        NOT NULL,
    note                 TEXT        CHECK (length(note) <= 280),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT transfers_distinct_accounts_ck CHECK (from_account_id <> to_account_id),
    CONSTRAINT transfers_reversal_link_ck CHECK ((type = 'REVERSAL') = (reverses_transfer_id IS NOT NULL)),
    CONSTRAINT transfers_fee_link_ck CHECK ((type = 'FEE') = (parent_transfer_id IS NOT NULL))
);
-- velocity + amount-spike rules and "my outgoing transfers" queries
CREATE INDEX transfers_from_created_idx ON transfers (from_account_id, created_at) INCLUDE (amount, status);
-- incoming side for statements / Q&A "received"
CREATE INDEX transfers_to_created_idx   ON transfers (to_account_id, created_at);
-- new-payee rule: "have I ever paid this account before?"
CREATE INDEX transfers_from_to_idx      ON transfers (from_account_id, to_account_id);
-- admin risk queue (partial: only the handful of HELD rows are indexed)
CREATE INDEX transfers_held_idx         ON transfers (created_at) WHERE status = 'HELD';

-- ---------------------------------------------------------------------
-- ledger_entries: the debit/credit lines. Insert-only.
-- Positive amount + separate direction column (see README for why).
-- ---------------------------------------------------------------------
CREATE TABLE ledger_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT      NOT NULL REFERENCES transfers (id),
    account_id  BIGINT      NOT NULL REFERENCES accounts (id),
    direction   TEXT        NOT NULL CHECK (direction IN ('DEBIT', 'CREDIT')),
    amount      BIGINT      NOT NULL CHECK (amount > 0),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- wallet statement: WHERE account_id = ? ORDER BY created_at DESC, id DESC
CREATE INDEX ledger_entries_account_created_idx ON ledger_entries (account_id, created_at DESC, id DESC);
-- entries of one transfer (GET /transfers/{id}, balance trigger, orphan check)
CREATE INDEX ledger_entries_transfer_idx ON ledger_entries (transfer_id);

-- Ledger entries are never updated or deleted. Mistakes are fixed with a
-- REVERSAL transfer. Enforced in the database, not only in code.
CREATE FUNCTION forbid_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only: % is not allowed', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER ledger_entries_append_only
    BEFORE UPDATE OR DELETE ON ledger_entries
    FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER ledger_entries_no_truncate
    BEFORE TRUNCATE ON ledger_entries
    FOR EACH STATEMENT EXECUTE FUNCTION forbid_mutation();

-- Debits and credits of one transfer must sum to the same amount.
-- Checked at COMMIT (deferred), because the lines are inserted one by one.
CREATE FUNCTION check_transfer_balanced() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    total_debit  BIGINT;
    total_credit BIGINT;
BEGIN
    SELECT COALESCE(SUM(amount) FILTER (WHERE direction = 'DEBIT'), 0),
           COALESCE(SUM(amount) FILTER (WHERE direction = 'CREDIT'), 0)
      INTO total_debit, total_credit
      FROM ledger_entries
     WHERE transfer_id = NEW.transfer_id;

    IF total_debit <> total_credit THEN
        RAISE EXCEPTION 'transfer % is unbalanced: debits=% credits=%',
            NEW.transfer_id, total_debit, total_credit
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER ledger_entries_balanced
    AFTER INSERT ON ledger_entries
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_transfer_balanced();

-- ---------------------------------------------------------------------
-- transfer_status_history: audit log of every status change.
-- Written by a trigger so no code path can change a status silently.
-- The application identifies itself with  set_config('app.actor', ..., true).
-- ---------------------------------------------------------------------
CREATE TABLE transfer_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT      NOT NULL REFERENCES transfers (id),
    from_status TEXT,
    to_status   TEXT        NOT NULL,
    changed_by  TEXT        NOT NULL,
    reason      TEXT,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX transfer_status_history_transfer_idx ON transfer_status_history (transfer_id, id);

CREATE TRIGGER transfer_status_history_append_only
    BEFORE UPDATE OR DELETE ON transfer_status_history
    FOR EACH ROW EXECUTE FUNCTION forbid_mutation();

CREATE FUNCTION log_transfer_status() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' OR NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO transfer_status_history (transfer_id, from_status, to_status, changed_by, reason)
        VALUES (NEW.id,
                CASE WHEN TG_OP = 'UPDATE' THEN OLD.status END,
                NEW.status,
                COALESCE(NULLIF(current_setting('app.actor', true), ''), 'db:' || current_user),
                NULLIF(current_setting('app.reason', true), ''));
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER transfers_status_audit
    AFTER INSERT OR UPDATE OF status ON transfers
    FOR EACH ROW EXECUTE FUNCTION log_transfer_status();

-- ---------------------------------------------------------------------
-- idempotency_keys: one row per (user, client key). The UNIQUE constraint
-- is what makes concurrent retries safe. NULLS NOT DISTINCT (PG15+) also
-- covers requests that have no owning user yet (POST /users, admin calls).
-- ---------------------------------------------------------------------
CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      REFERENCES users (id),
    idempotency_key UUID        NOT NULL,
    request_method  TEXT        NOT NULL,
    request_path    TEXT        NOT NULL,
    request_hash    CHAR(64)    NOT NULL,   -- SHA-256 hex of method + path + canonical body
    status          TEXT        NOT NULL CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    response_code   INT,
    response_body   TEXT,       -- stored verbatim so a replay is byte-for-byte identical
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at    TIMESTAMPTZ,
    CONSTRAINT idempotency_keys_user_key_uq UNIQUE NULLS NOT DISTINCT (user_id, idempotency_key)
);
-- nightly cleanup of keys older than 24h
CREATE INDEX idempotency_keys_created_idx ON idempotency_keys (created_at);

-- ---------------------------------------------------------------------
-- Fraud rules: thresholds live in data, not code.
-- ---------------------------------------------------------------------
CREATE TABLE risk_rules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             TEXT        NOT NULL UNIQUE
                                 CHECK (code IN ('VELOCITY', 'AMOUNT_SPIKE', 'NEW_PAYEE_LARGE')),
    description      TEXT        NOT NULL,
    action           TEXT        NOT NULL CHECK (action IN ('HOLD', 'FLAG')),
    enabled          BOOLEAN     NOT NULL DEFAULT true,
    window_minutes   INT         CHECK (window_minutes > 0),
    max_count        INT         CHECK (max_count >= 0),
    multiplier       NUMERIC(8, 2) CHECK (multiplier > 0),
    lookback_days    INT         CHECK (lookback_days > 0),
    amount_threshold BIGINT      CHECK (amount_threshold >= 0),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE risk_flags (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id     BIGINT      NOT NULL REFERENCES transfers (id),
    rule_id         BIGINT      NOT NULL REFERENCES risk_rules (id),
    action          TEXT        NOT NULL CHECK (action IN ('HOLD', 'FLAG')),
    details         JSONB       NOT NULL DEFAULT '{}',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- filled by the nightly LLM explanation step
    llm_label       TEXT        CHECK (llm_label IN ('likely_ok', 'review', 'likely_fraud')),
    llm_explanation TEXT,
    explained_at    TIMESTAMPTZ,
    CONSTRAINT risk_flags_transfer_rule_uq UNIQUE (transfer_id, rule_id)
);
CREATE INDEX risk_flags_created_idx ON risk_flags (created_at);

-- ---------------------------------------------------------------------
-- Reconciliation
-- ---------------------------------------------------------------------
CREATE TABLE job_locks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name         TEXT        NOT NULL UNIQUE,
    last_started_at  TIMESTAMPTZ,
    last_finished_at TIMESTAMPTZ
);

CREATE TABLE reconciliation_runs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triggered_by      TEXT        NOT NULL,
    status            TEXT        NOT NULL
                                  CHECK (status IN ('RUNNING', 'PASSED', 'FAILED', 'SKIPPED', 'ERROR')),
    started_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at       TIMESTAMPTZ,
    checks_run        INT         NOT NULL DEFAULT 0,
    issues_found      INT         NOT NULL DEFAULT 0,
    accounts_checked  BIGINT,
    transfers_checked BIGINT,
    entries_checked   BIGINT,
    flags_explained   INT         NOT NULL DEFAULT 0,
    keys_purged       INT         NOT NULL DEFAULT 0,
    error             TEXT
);

CREATE TABLE reconciliation_issues (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      BIGINT      NOT NULL REFERENCES reconciliation_runs (id),
    check_name  TEXT        NOT NULL,
    entity_type TEXT        NOT NULL,   -- LEDGER | TRANSFER | ACCOUNT | LEDGER_ENTRY
    entity_id   BIGINT,
    expected    BIGINT,
    actual      BIGINT,
    details     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX reconciliation_issues_run_idx ON reconciliation_issues (run_id);
